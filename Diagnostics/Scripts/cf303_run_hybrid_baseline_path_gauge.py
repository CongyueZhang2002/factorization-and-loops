#!/usr/bin/env python3
"""Generate and optionally run the exact CF303 zero-block-1 baseline gauge.

The mathematical recurrence remains the single legacy Maple implementation.
This launcher only binds it to distinct hybrid-baseline inputs and outputs;
canonical runtime files are never swapped or overwritten.
"""

from __future__ import annotations

import argparse
import subprocess
from pathlib import Path


ROOT = Path("/home/maxzhang/factorization-and-loops-codex")
SCRIPTS = ROOT / "Diagnostics/Scripts"
RUNTIME = ROOT / "Runtime/2026-08-31_cf303_native_dlog_residues"
SOURCE = SCRIPTS / "build_cf303_block25_finite_path_gauge.mpl"
GENERATED = RUNTIME / "cf303_hybrid_baseline_finite_path_gauge_generated.mpl"
TRANSFER = RUNTIME / "cf303_hybrid_baseline90_transfer.maple"
PATH_INPUT = RUNTIME / "cf303_hybrid_baseline_path_dlog_gauge_inputs.maple"
OUTPUT_MAPLE = RUNTIME / "cf303_hybrid_baseline_finite_path_gauge.maple"
OUTPUT_WL = RUNTIME / "cf303_hybrid_baseline_finite_path_gauge.wl"


REPLACEMENTS = (
    (
        '  "/cf303_block25_general_elliptic_transfer.maple"):',
        '  "/cf303_hybrid_baseline90_transfer.maple"):',
    ),
    (
        '  "/cf303_block25_path_dlog_gauge_inputs.maple"):',
        '  "/cf303_hybrid_baseline_path_dlog_gauge_inputs.maple"):',
    ),
    (
        '  "/cf303_block25_finite_path_gauge.maple"):',
        '  "/cf303_hybrid_baseline_finite_path_gauge.maple"):',
    ),
    (
        '  "/cf303_block25_finite_path_gauge.wl"):',
        '  "/cf303_hybrid_baseline_finite_path_gauge.wl"):',
    ),
    (
        "exceptionBlocksExpected := [1,2,11,14,18]:",
        "exceptionBlocksExpected := []:",
    ),
    (
        'transferStatus<>"CF303Block25GeneralEllipticTransferAcceptedV1"',
        'transferStatus<>"CF303Block25HybridBaselineTransferWithZeroBlock1V1"',
    ),
    (
        '"CF303Block25FinitePathGaugeAcceptedV1"',
        '"CF303Block25HybridBaselineFinitePathGaugeAcceptedV1"',
    ),
    (
        '"CF303Block25FinitePathGaugeFailedV1"',
        '"CF303Block25HybridBaselineFinitePathGaugeFailedV1"',
    ),
)


def derive_script() -> None:
    text = SOURCE.read_text()
    if "windowLow := -3:" not in text or "windowHigh := 4:" not in text:
        raise RuntimeError("legacy recurrence does not carry the required -3..4 window")
    for old, new in REPLACEMENTS:
        count = text.count(old)
        if count != 1:
            raise RuntimeError(f"expected one binding site, found {count}: {old}")
        text = text.replace(old, new)
    header = (
        "# GENERATED by cf303_run_hybrid_baseline_path_gauge.py.\n"
        "# Exact algorithm source: build_cf303_block25_finite_path_gauge.mpl.\n"
        "# Inputs and outputs are deliberately distinct from canonical runtime files.\n"
    )
    GENERATED.write_text(header + text)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--run", action="store_true",
                        help="run Maple after generating the bound script")
    args = parser.parse_args()
    missing = [str(path) for path in (SOURCE, TRANSFER, PATH_INPUT)
               if not path.is_file()]
    if missing:
        raise RuntimeError(f"missing prerequisite(s): {missing}")
    derive_script()
    print(f"generated={GENERATED}")
    print(f"output_maple={OUTPUT_MAPLE}")
    print(f"output_wolfram={OUTPUT_WL}")
    if args.run:
        subprocess.run(["maple", "-q", str(GENERATED)], cwd=ROOT, check=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
