#!/usr/bin/env bash
# Submit a Wolfram script as a mission to the running KernelPool.
# Usage: kpsubmit.sh <name> <script.wls|.wl> [args...]     (args -> $ScriptCommandLine inside the mission)
#        POOL=<pooldir> to override the pool directory.
#        FACET_TASK_BROKER_MAX_HELPERS=<nonnegative integer> is captured
#        into this mission (it does not rely on changing a live kernel's
#        process environment).
#        FACET_RESOURCE_GROUP, FACET_RESOURCE_ROLE and FACET_RESOURCE_OWNER
#        identify the mission to the pool-owned resource allocator.
# The mission runs on a free subkernel via Get; its Print/Message output goes to <pool>/logs/<name>.log;
# on completion <pool>/done/<name>.status (or failed/) holds the result record.
set -euo pipefail
POOL="${POOL:-/tmp/claude-1000/-home-maxzhang/97c0fce7-1578-4630-a481-38730c7f8b9d/scratchpad/kernelpool}"
if (( $# < 2 )); then
  echo "Usage: kpsubmit.sh <name> <script.wls|.wl> [args...]" >&2
  exit 64
fi
name="$1"; target="$2"; shift 2
if [[ ! "$name" =~ ^[A-Za-z0-9][A-Za-z0-9._-]*$ || ${#name} -gt 180 ]]; then
  echo "kpsubmit: mission name must be 1-180 characters from [A-Za-z0-9._-], starting alphanumeric" >&2
  exit 64
fi
if [[ ! -f "$target" ]]; then
  echo "kpsubmit: target is not a regular file: $target" >&2
  exit 66
fi
script="$(readlink -f -- "$target"; printf '\001')"
script="${script%$'\001'}"
script="${script%$'\n'}"
if [[ -z "$script" || ! -f "$script" ]]; then
  echo "kpsubmit: could not resolve target: $target" >&2
  exit 66
fi
[ -f "$POOL/pool.pid" ] && kill -0 "$(cat "$POOL/pool.pid")" 2>/dev/null || { echo "kpsubmit: pool not running at $POOL" >&2; exit 2; }
helper_limit="${FACET_TASK_BROKER_MAX_HELPERS:-}"
if [[ -n "$helper_limit" && ! "$helper_limit" =~ ^[0-9]+$ ]]; then
  echo "kpsubmit: FACET_TASK_BROKER_MAX_HELPERS must be a nonnegative integer" >&2
  exit 64
fi
helper_limit="${helper_limit:-Infinity}"
resource_group="${FACET_RESOURCE_GROUP:-ungrouped}"
resource_role="${FACET_RESOURCE_ROLE:-mission}"
owner_suffix="$(date +%s%N)_$$"
default_owner="${name:0:150}_$owner_suffix"
resource_owner="${FACET_RESOURCE_OWNER:-$default_owner}"
if [[ ! "$resource_group" =~ ^[A-Za-z0-9][A-Za-z0-9._-]{0,179}$ ]]; then
  echo "kpsubmit: FACET_RESOURCE_GROUP is not a safe resource name" >&2
  exit 64
fi
if [[ ! "$resource_role" =~ ^[A-Za-z][A-Za-z0-9._-]{0,63}$ ]]; then
  echo "kpsubmit: FACET_RESOURCE_ROLE is not a safe role name" >&2
  exit 64
fi
if [[ ! "$resource_owner" =~ ^[A-Za-z0-9][A-Za-z0-9._-]{0,179}$ ]]; then
  echo "kpsubmit: FACET_RESOURCE_OWNER is not a safe resource name" >&2
  exit 64
fi

# Encode shell values as literal Wolfram strings.  Direct interpolation is not
# safe: a quote or backslash in a path/argument can change the generated
# wrapper's syntax, and a newline can move text outside the intended string.
wolfram_string_literal() {
  local value="$1"
  value="${value//\\/\\\\}"
  value="${value//\"/\\\"}"
  value="${value//$'\r'/\\r}"
  value="${value//$'\n'/\\n}"
  value="${value//$'\t'/\\t}"
  printf '"%s"' "$value"
}

script_literal="$(wolfram_string_literal "$script")"
directory="$(dirname -- "$script"; printf '\001')"
directory="${directory%$'\001'}"
directory="${directory%$'\n'}"
directory_literal="$(wolfram_string_literal "$directory")"
resource_group_literal="$(wolfram_string_literal "$resource_group")"
resource_role_literal="$(wolfram_string_literal "$resource_role")"
resource_owner_literal="$(wolfram_string_literal "$resource_owner")"
argl="$script_literal"
for argument in "$@"; do
  argl+=", $(wolfram_string_literal "$argument")"
done
tmp="$POOL/queue/.$name.wl.tmp"
cat > "$tmp" <<WL
(* KernelPool mission wrapper generated by kpsubmit.sh. *)
(* FACET_RESOURCE group=$resource_group role=$resource_role owner=$resource_owner *)
Block[{KernelPoolMission\`\$TaskBrokerMaxHelpers = $helper_limit,
    KernelPoolMission\`\$TaskBrokerResourceGroup = $resource_group_literal,
    KernelPoolMission\`\$TaskBrokerResourceRole = $resource_role_literal,
    KernelPoolMission\`\$TaskBrokerResourceOwner = $resource_owner_literal},
  Module[{KernelPoolMission\`Private\`res,
      KernelPoolMission\`Private\`sourceText,
      KernelPoolMission\`Private\`sourceLines,
      KernelPoolMission\`Private\`parseText,
      KernelPoolMission\`Private\`parsed,
      KernelPoolMission\`Private\`parseContext,
      KernelPoolMission\`Private\`globalBefore,
      KernelPoolMission\`Private\`newGlobal,
      KernelPoolMission\`Private\`parseFailed,
      KernelPoolMission\`Private\`parseCleanup},
    Unprotect[\$ScriptCommandLine]; \$ScriptCommandLine = {$argl};
    SetDirectory[$directory_literal];
    (* The pool parses this generated wrapper, but Get can report a syntax
       error in its target and still return Null.  Parse the actual target
       under HoldComplete first so malformed code can never be filed OK.
       WolframScript's optional shebang is outside the Wolfram grammar. *)
    KernelPoolMission\`Private\`sourceText =
      Quiet[Check[Import[$script_literal, "Text"], \$Failed]];
    If[! StringQ[KernelPoolMission\`Private\`sourceText],
      Print["KPSUBMIT TARGET IMPORT FAILURE: " <> $script_literal];
      \$Failed,
      KernelPoolMission\`Private\`sourceLines =
        StringSplit[KernelPoolMission\`Private\`sourceText, "\n"];
      KernelPoolMission\`Private\`parseText =
        If[KernelPoolMission\`Private\`sourceLines =!= {} &&
            StringStartsQ[First[KernelPoolMission\`Private\`sourceLines], "#!"],
          StringRiffle[Rest[KernelPoolMission\`Private\`sourceLines], "\n"],
          KernelPoolMission\`Private\`sourceText];
      (* A held parse still interns symbols.  Parse with only System\` on the
         context path, then delete its unique temporary context and any
         explicitly-qualified Global\` symbols created by validation.  The
         later Get therefore sees exactly the namespace it would have seen
         without this syntax gate. *)
      KernelPoolMission\`Private\`parseContext =
        "KernelPoolTargetParse\`c" <>
          StringReplace[CreateUUID[], "-" -> ""] <> "\`";
      KernelPoolMission\`Private\`globalBefore =
        System\`Names["Global\`*"];
      KernelPoolMission\`Private\`parseCleanup := (
        KernelPoolMission\`Private\`parsed =.;
        KernelPoolMission\`Private\`newGlobal =
          Complement[System\`Names["Global\`*"],
            KernelPoolMission\`Private\`globalBefore];
        Scan[(Quiet[System\`Remove[#]]) &,
          KernelPoolMission\`Private\`newGlobal];
        Quiet[System\`Remove[
          KernelPoolMission\`Private\`parseContext <> "*"]]);
      KernelPoolMission\`Private\`parsed =
        CheckAbort[
          Block[{\$Context = KernelPoolMission\`Private\`parseContext,
              \$ContextPath = {"System\`"}},
            Quiet[Check[
              ToExpression[KernelPoolMission\`Private\`parseText,
                InputForm, HoldComplete], \$Failed]]],
          (KernelPoolMission\`Private\`parseCleanup; Abort[])];
      KernelPoolMission\`Private\`parseFailed =
        KernelPoolMission\`Private\`parsed === \$Failed ||
          Head[KernelPoolMission\`Private\`parsed] =!= HoldComplete;
      KernelPoolMission\`Private\`parseCleanup;
      If[TrueQ[KernelPoolMission\`Private\`parseFailed],
        Print["KPSUBMIT TARGET PARSE FAILURE: " <> $script_literal];
        \$Failed,
        KernelPoolMission\`Private\`res = Get[$script_literal];
        KernelPoolMission\`Private\`res]]]]
WL
mv "$tmp" "$POOL/queue/$name.wl"
echo "queued $name -> $POOL/queue/$name.wl ; log $POOL/logs/$name.log ; wait: kpwait.sh $name"
