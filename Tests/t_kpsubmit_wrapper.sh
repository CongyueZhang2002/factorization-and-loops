#!/usr/bin/env bash
# Shell-only checks for kpsubmit's generated Wolfram wrapper.  This uses a
# fake live pool PID and never starts or contacts a Wolfram kernel.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
submit="$root/Scripts/kpsubmit.sh"
server="$root/Scripts/KernelPool.wls"
test_root="$(mktemp -d /tmp/feynfacet-kpsubmit-test.XXXXXX)"
pool="$test_root/pool"
target="$test_root/"$'target"back\\slash\rline\nline\ttarget.wls'
failures=0

cleanup() {
  case "$test_root" in
    /tmp/feynfacet-kpsubmit-test.*) rm -rf -- "$test_root" ;;
  esac
}
trap cleanup EXIT

mkdir -p "$pool/queue"
printf '%s\n' "$$" > "$pool/pool.pid"
printf '%s\n' '#!/usr/bin/env wolframscript' '0' > "$target"

POOL="$pool" FACET_TASK_BROKER_MAX_HELPERS=2 "$submit" wrapper_roundtrip \
  "$target" plain 'quote"arg' 'back\slash' $'cr\rvalue' \
  $'line1\nline2' $'tab\tvalue' 'close*)comment' >/dev/null
wrapper="$pool/queue/wrapper_roundtrip.wl"

assert_contains() {
  local description="$1" needle="$2"
  if grep -Fq -- "$needle" "$wrapper"; then
    printf 'PASS  %s\n' "$description"
  else
    printf 'FAIL  %s\n' "$description"
    failures=$((failures + 1))
  fi
}

assert_file_contains() {
  local description="$1" file="$2" needle="$3"
  if grep -Fq -- "$needle" "$file"; then
    printf 'PASS  %s\n' "$description"
  else
    printf 'FAIL  %s\n' "$description"
    failures=$((failures + 1))
  fi
}

assert_contains "wrapper has a static noninjectable comment" \
  '(* KernelPool mission wrapper generated by kpsubmit.sh. *)'
assert_contains "mission helper ceiling is captured" \
  'KernelPoolMission`$TaskBrokerMaxHelpers = 2'
assert_contains "target quote, backslash and controls are Wolfram-escaped" \
  'target\"back\\slash\rline\nline\ttarget.wls'
assert_contains "quote in argv is Wolfram-escaped" '"quote\"arg"'
assert_contains "backslash in argv is Wolfram-escaped" '"back\\slash"'
assert_contains "carriage return in argv is Wolfram-escaped" '"cr\rvalue"'
assert_contains "newline in argv is Wolfram-escaped" '"line1\nline2"'
assert_contains "tab in argv is Wolfram-escaped" '"tab\tvalue"'
assert_contains "comment terminator remains inside an argv string" \
  '"close*)comment"'
assert_contains "target parse uses a unique disposable context" \
  '"KernelPoolTargetParse`c" <>'
assert_contains "target parse sees only System context" \
  '$ContextPath = {"System`"}'
assert_contains "held target parse is released before cleanup" \
  'KernelPoolMission`Private`parsed =.;'
assert_contains "target parse removes its disposable symbols" \
  'System`Remove['
assert_contains "target parse removes newly interned Global symbols" \
  'Complement[System`Names["Global`*"],'
assert_contains "target symbol-table reads bypass package shadowing" \
  'System`Names["Global`*"]'
assert_contains "target parse cleans and rethrows an abort" \
  '(KernelPoolMission`Private`parseCleanup; Abort[])'
assert_file_contains "server wrapper parse uses a unique disposable context" \
  "$server" 'missionParseContext = "KernelPoolWrapperParse`c" <>'
assert_file_contains "server wrapper parse sees only System context" \
  "$server" '$Context = missionParseContext, $ContextPath = {"System`"}'
assert_file_contains "server held wrapper parse is released before cleanup" \
  "$server" 'missionParsed =.;'
assert_file_contains "server wrapper parse removes its disposable symbols" \
  "$server" 'System`Remove[missionParseContext <> "*"]'
assert_file_contains "server wrapper parse removes newly interned Global symbols" \
  "$server" 'System`Names["Global`*"], missionGlobalBefore'
assert_file_contains "server symbol-table reads bypass package shadowing" \
  "$server" 'missionGlobalBefore = System`Names["Global`*"]'
assert_file_contains "server wrapper parse cleans and rethrows an abort" \
  "$server" '(missionParseCleanup; Abort[])'

if LC_ALL=C grep -q $'\r' "$wrapper"; then
  printf 'FAIL  generated wrapper contains a literal carriage return\n'
  failures=$((failures + 1))
else
  printf 'PASS  generated wrapper contains no literal carriage return\n'
fi

if POOL="$pool" "$submit" '../escape' "$target" >/dev/null 2>&1; then
  printf 'FAIL  traversal mission name was accepted\n'
  failures=$((failures + 1))
else
  printf 'PASS  traversal mission name is rejected\n'
fi
if POOL="$pool" "$submit" 'bad/name' "$target" >/dev/null 2>&1; then
  printf 'FAIL  slash mission name was accepted\n'
  failures=$((failures + 1))
else
  printf 'PASS  slash mission name is rejected\n'
fi
if POOL="$pool" "$submit" missing_target \
    "$test_root/does-not-exist.wls" >/dev/null 2>&1; then
  printf 'FAIL  missing target was accepted\n'
  failures=$((failures + 1))
else
  printf 'PASS  missing target is rejected\n'
fi

if (( failures > 0 )); then
  printf '%s shell assertions failed\n' "$failures"
  exit 1
fi
printf '27 shell assertions, 0 failed\n'
